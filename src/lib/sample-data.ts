export const sampleDashboardStats: DashboardStats = {
  totalRepos: sampleRepositories.length,
  totalStars: sampleRepositories.reduce((sum, r) => sum + r.stars, 0),
  totalLanguages: new Set(sampleRepositories.map((r) => r.language).filter(Boolean)).size,
  totalTopics: new Set(sampleRepositories.flatMap((r) => r.topics)).size,
  recentlyAdded: 5,
};

export const sampleLanguageStats: LanguageStat[] = (() => {
  const counts: Record<string, number> = {};
  sampleRepositories.forEach((r) => {
    if (r.language) counts[r.language] = (counts[r.language] || 0) + 1;
  });
  const total = sampleRepositories.length;
  return Object.entries(counts)
    .map(([language, count]) => ({
      language,
      count,
      percentage: Math.round((count / total) * 100),
    }))
    .sort((a, b) => b.count - a.count);
})();

export const sampleTopicStats: TopicStat[] = (() => {
  const counts: Record<string, number> = {};
  sampleRepositories.forEach((r) => {
    r.topics.forEach((t) => {
      counts[t] = (counts[t] || 0) + 1;
    });
  });
  return Object.entries(counts)
    .map(([topic, count]) => ({ topic, count }))
    .sort((a, b) => b.count - a.count)
    .slice(0, 15);
})();

